// scripts/build-faust-cpp.mjs -- compiles every native-engine/Source/dsp/faust/*.dsp to C++
// with the native Faust compiler, pinned to native-engine/Source/dsp/faust/FAUST_VERSION
// (Homebrew's `faust`, `brew pin`ned; a build-time tool only, nothing of it ships).
//   node scripts/build-faust-cpp.mjs
//
// The .dsp files are the single copy: ell.ing/radio compiles the same files to wasm with
// @grame/faustwasm at the same Faust version (its scripts/build-faust.mjs).
//
// For each <name>.dsp it writes generated/<name>.h: class <Name>Dsp in namespace sssketch::faust,
// built on our own architecture (arch.cpp + FaustArch.h; no GRAME architecture file, see
// LICENSES.md). The headers are committed; scripts/buildFaustCpp.test.ts regenerates them and
// fails on any byte of drift. The compiler runs inside the faust directory with relative paths,
// so nothing machine-specific lands in the output.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const FAUST_DIR = join(ROOT, 'native-engine', 'Source', 'dsp', 'faust')
export const GENERATED_DIR = join(FAUST_DIR, 'generated')
export const PINNED_VERSION = readFileSync(join(FAUST_DIR, 'FAUST_VERSION'), 'utf8').trim()
/** The web's options (-ftz 2: flush denormals to zero by masking; single precision), plus -i
 *  (inline the architecture's includes; ours has only its own), our architecture file, and
 *  -fm arch: the math functions are called fast_<fn>f and defined in FaustArch.h, in double
 *  precision rounded to float, as the web's wasm gets them from JavaScript's Math; and -fp (full
 *  parentheses), so a long sum is added in the order Faust built it -- without it the C++
 *  printer drops the brackets and C++'s left-to-right addition rounds differently from the
 *  wasm, which keeps Faust's order (the true-peak detector came out 1.4e-6 off the web). */
export const COMPILE_ARGS = [
  '-lang',
  'cpp',
  '-i',
  '-a',
  'arch.cpp',
  '-ftz',
  '2',
  '-single',
  '-fm',
  'arch',
  '-fp'
]
const FAUST = process.env.FAUST ?? 'faust'

/** The installed compiler's version ("2.88.0"), or null when there is no `faust`. */
export function installedVersion() {
  try {
    const out = execFileSync(FAUST, ['--version'], { encoding: 'utf8' })
    return /Version\s+(\S+)/.exec(out)?.[1] ?? null
  } catch {
    return null
  }
}

export const dspNames = () =>
  readdirSync(FAUST_DIR)
    .filter((f) => f.endsWith('.dsp'))
    .map((f) => f.slice(0, -4))
    .sort()

/** "truepeak" -> "TruepeakDsp" */
export const className = (name) => name[0].toUpperCase() + name.slice(1) + 'Dsp'

/** generated/<name>.h's text for one .dsp. Refuses a compiler other than the pinned one. */
export function generate(name) {
  const version = installedVersion()
  if (version !== PINNED_VERSION)
    throw new Error(`faust ${version ?? 'not found'}, pinned ${PINNED_VERSION} (FAUST_VERSION)`)
  const source = readFileSync(join(FAUST_DIR, `${name}.dsp`))
  const code = execFileSync(FAUST, [...COMPILE_ARGS, '-cn', className(name), `${name}.dsp`], {
    cwd: FAUST_DIR,
    encoding: 'utf8'
  })
  const sha = createHash('sha256').update(source).digest('hex')
  return (
    `// GENERATED by scripts/build-faust-cpp.mjs -- do not edit. Regenerate: node scripts/build-faust-cpp.mjs\n` +
    `// from ${name}.dsp (sha256 ${sha}) with Faust ${version}\n` +
    `// licence: the .dsp's, GPL-2.0-or-later (see ../LICENSES.md)\n` +
    code
  )
}

export function generateAll(outDir = GENERATED_DIR) {
  mkdirSync(outDir, { recursive: true })
  const written = []
  for (const name of dspNames()) {
    const text = generate(name)
    writeFileSync(join(outDir, `${name}.h`), text)
    written.push({ name, bytes: text.length })
  }
  return written
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const { name, bytes } of generateAll())
    console.log(`${name}: generated/${name}.h, ${bytes} bytes (faust ${PINNED_VERSION})`)
}
